    'and "you" rather than formal legal writing. Explain the rule in your own '
    'words instead of copying the source wording. Avoid legal jargon when an '
    'ordinary phrase preserves the same meaning. When a legal term is necessary, '
    'give its brief everyday meaning immediately on first use. Expand an unfamiliar '
    'agency acronym on first use when its meaning is established; never guess it. '
    'Actively replace stiff or technical phrasing with everyday wording; do not assume '
